/**
 * GJB8114 规则测试用例 - 不确定规则组
 *
 * 覆盖规则：
 *   R-1-10-4  指针变量的赋值类型必须与指针变量类型一致
 *   R-1-1-11  变量禁止未赋值就使用（此处指 R-1-11，未初始化使用）
 *   R-1-6-12  除法运算中禁止被零除
 *   R-1-6-14  缓存区读取禁止操作越界
 *   R-1-6-15  缓存区写入禁止操作越界
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

#define BUF_SIZE 8


/* ================================================================
 * R-1-10-4  BUG: 指针赋值类型不一致
 *
 * 规则要求：赋给指针变量的值，其类型必须与指针所指类型完全一致。
 * 此处将 double* 赋给 int*，绕过类型系统，在解引用时
 * 读取的字节数和解释方式均不正确，产生未定义行为。
 * ================================================================ */
void r1_10_4_demo(void)
{
    double dval = 3.14;

    /* BUG R-1-10-4: 将 double* 强制赋给 int*，类型不一致 */
    int *iptr = (int *)&dval;

    /* 解引用时只读了 double 前 4 字节，结果毫无意义 */
    printf("r1_10_4: *iptr = %d  (应为 3.14 的 int 解读，结果无意义)\n", *iptr);
}


/* ================================================================
 * R-1-11  BUG: 变量未赋值就使用（未初始化变量）
 *
 * 规则要求：变量在使用前必须明确赋值。
 * 下面的 sum 只在 count > 0 时初始化，当 count == 0
 * 时直接返回 sum，读取了未初始化的栈内存。
 * ================================================================ */
int r1_11_compute_average(int count)
{
    int sum;           /* BUG R-1-11: 未初始化 */

    if (count > 0) {
        sum = count * 10;  /* 仅在 count>0 时赋值 */
    }
    /* count==0 时 sum 未初始化，使用了垃圾值 */
    return sum / (count == 0 ? 1 : count);
}

void r1_11_demo(void)
{
    int result = r1_11_compute_average(0);   /* 触发未初始化路径 */
    printf("r1_11: average(0) = %d  (结果为垃圾值)\n", result);
}


/* ================================================================
 * R-1-6-12  BUG: 除法运算中被除数可能为零
 *
 * 规则要求：在执行除法之前必须确保除数不为零。
 * 下面的函数直接用外部传入的 divisor 做除法，
 * 没有任何零值检查，当 divisor==0 时产生除零错误。
 * ================================================================ */
int r1_6_12_divide(int dividend, int divisor)
{
    /* BUG R-1-6-12: divisor 未做零检查就直接用作除数 */
    return dividend / divisor;
}

void r1_6_12_demo(void)
{
    int a = 100, b = 0;
    /* b==0，下一行将触发除零 */
    int result = r1_6_12_divide(a, b);
    printf("r1_6_12: 100/0 = %d  (除零，未定义行为)\n", result);
}


/* ================================================================
 * R-1-6-14  BUG: 缓冲区读取越界
 *
 * 规则要求：读取缓冲区时下标不得超出合法范围。
 * 下面循环的上界是 BUF_SIZE+2，超出了数组长度 BUF_SIZE，
 * 导致读取越界内存。
 * ================================================================ */
void r1_6_14_demo(void)
{
    uint8_t buf[BUF_SIZE];
    int i;

    /* 初始化合法区域 */
    for (i = 0; i < BUF_SIZE; i++) {
        buf[i] = (uint8_t)i;
    }

    /* BUG R-1-6-14: 循环上界 BUF_SIZE+2 超出数组长度，读取越界 */
    int sum = 0;
    for (i = 0; i < BUF_SIZE + 2; i++) {
        sum += buf[i];   /* i = BUF_SIZE, BUF_SIZE+1 时越界读 */
    }
    printf("r1_6_14: sum = %d  (包含越界读取的垃圾值)\n", sum);
}


/* ================================================================
 * R-1-6-15  BUG: 缓冲区写入越界
 *
 * 规则要求：向缓冲区写入时下标不得超出合法范围。
 * 下面调用 memcpy 时源长度超过目标缓冲区大小，
 * 导致栈上相邻内存被覆盖写。
 * ================================================================ */
void r1_6_15_demo(void)
{
    char dst[BUF_SIZE];                  /* 目标缓冲区 8 字节 */
    const char src[] = "HELLO_OVERFLOW"; /* 源数据 15 字节（含 '\0' 共 15） */

    /* BUG R-1-6-15: 拷贝长度 sizeof(src)=15 超过 dst 容量 8，写越界 */
    memcpy(dst, src, sizeof(src));

    printf("r1_6_15: dst = %.8s  (已写越界，栈数据被破坏)\n", dst);
}


/* ================================================================
 * 入口：依次运行所有不确定规则演示函数
 * ================================================================ */
int main_uncertain(void)
{
    r1_10_4_demo();
    r1_11_demo();
    r1_6_12_demo();
    r1_6_14_demo();
    r1_6_15_demo();
    return 0;
}
