/**
 * GJB8114 规则测试用例 - 确定规则组
 *
 * 覆盖规则：
 *   R-1-1-1   禁止通过定义改变关键字和基本类型含义
 *   R-1-1-10  位定义的有符号整型变量位长必须大于1
 *   R-1-1-11  位定义的整数类型变量必须明确定义是有符号还是无符号的
 *   R-1-1-12  位定义变量必须是同长度类型定义位置，禁止跨越类型的长度
 *   R-1-1-13  函数声明中必须对参数类型进行声明，并带有变量名
 */

#include <stdio.h>
#include <stdint.h>


/* ================================================================
 * R-1-1-1  BUG: 用 #define 重新定义基本类型 int 的含义
 *
 * 规则要求：不允许通过宏将关键字或基本类型改变为其他含义。
 * 此处将 int 重定义为 long，导致后续代码中 int 实际是 long，
 * 破坏了基本类型含义，属于典型违规。
 * ================================================================ */
#define int long   /* BUG R-1-1-1 */

void r1_1_1_demo(void)
{
    int x = 100;   /* 实际类型是 long，误导读者和工具 */
    printf("r1_1_1 x = %ld\n", x);
}

#undef int   /* 撤销，避免污染后续代码 */


/* ================================================================
 * R-1-1-10  BUG: 有符号位域宽度为 1
 *
 * 规则要求：signed 位域的位宽必须 > 1。
 * 宽度为 1 的 signed 位域只能表示 0 和 -1，无法表示正数，
 * 赋值行为违反直觉，极易引发逻辑错误。
 * ================================================================ */
typedef struct {
    signed int flag  : 1;   /* BUG R-1-1-10: 有符号位域宽度=1，赋 1 实际得到 -1 */
    signed int value : 4;   /* OK: 宽度 > 1 */
    unsigned int ctrl : 3;  /* OK: unsigned 不受此规则限制 */
} RegBits_t;

void r1_1_10_demo(void)
{
    RegBits_t r;
    r.flag  = 1;   /* 期望 1，实际存储 -1（符号扩展） */
    r.value = 5;
    printf("r1_1_10 flag=%d value=%d\n", r.flag, r.value);
}


/* ================================================================
 * R-1-1-11  BUG: 位域使用裸 int（符号性不明确）
 *
 * 规则要求：位域必须显式写 signed int 或 unsigned int，
 * 不允许使用未加符号限定词的 int，因为 int 位域的
 * 符号性是实现定义行为，不同编译器结果不同。
 * ================================================================ */
typedef struct {
    int          mode : 3;  /* BUG R-1-1-11: 裸 int，符号性不明确 */
    unsigned int en   : 1;  /* OK */
    signed int   cnt  : 4;  /* OK */
} CtrlReg_t;

void r1_1_11_demo(void)
{
    CtrlReg_t c;
    c.mode = 3;
    c.en   = 1;
    c.cnt  = -2;
    printf("r1_1_11 mode=%d en=%u cnt=%d\n", c.mode, c.en, c.cnt);
}


/* ================================================================
 * R-1-1-12  BUG: 位域跨越底层存储单元边界
 *
 * 规则要求：位域的起始偏移加上宽度不得超过底层类型的大小。
 * 此处在 uint8_t 结构中声明两个宽度为 5 bit 的字段，
 * 合计 10 bit 超过 uint8_t 的 8 bit，跨越了类型边界，
 * 行为由编译器实现定义，不可移植。
 * ================================================================ */
typedef struct {
    uint8_t high : 5;   /* OK  : bits [4:0] 未越界 */
    uint8_t low  : 5;   /* BUG R-1-1-12: bits [9:5] 跨越 uint8_t 的 8-bit 边界 */
} PackedByte_t;

void r1_1_12_demo(void)
{
    PackedByte_t p;
    p.high = 0x1F;
    p.low  = 0x1F;
    printf("r1_1_12 high=0x%X low=0x%X\n", p.high, p.low);
}


/* ================================================================
 * R-1-1-13  BUG: 函数声明参数列表缺少类型和变量名（K&R 风格）
 *
 * 规则要求：函数原型必须为每个参数显式声明类型并提供形参名。
 * 空括号 () 在 C 中表示"参数未指定"，不是"无参数"，
 * 编译器不进行参数类型检查，传入错误类型不报错。
 * ================================================================ */

/* BUG R-1-1-13: 原型没有参数类型和变量名 */
int r1_1_13_add();

/* K&R 风格函数定义，与现代 C 不兼容 */
int r1_1_13_add(a, b)
int a;
int b;
{
    return a + b;
}

void r1_1_13_demo(void)
{
    /* 传入浮点数编译器也不报错，因为原型没有类型信息 */
    int result = r1_1_13_add(3, 4);
    printf("r1_1_13 3+4=%d\n", result);
}
