"""
任务规划提示词模板

用于从影响域分析报告中提取和规划回归测试任务
"""

def get_task_planning_prompt():
    """
    获取任务规划阶段的提示词
    
    Returns:
        str: 任务规划提示词模板
    """
    return """你是一个专业的软件回归测试分析专家。请根据影响域分析报告，提取并规划回归测试任务。

## 任务目标
从影响域分析报告中识别所有变更条目，并为每个条目创建一个回归测试任务。

## 影响域报告结构理解
影响域分析报告通常包含以下章节：
- 3.1 需求变更及其影响域分析
- 3.2 设计变更及其影响域分析  
- 3.3 代码变更及其影响分析

每个章节可能包含多个变更条目，每个条目通常包含：
- 变更依据/标识号
- 变更说明/描述
- 影响范围
- 性能指标要求
- 限制与约束等

## 任务识别规则

### 1. 需求变更任务识别
在影响域分析报告的"3.1 需求变更及其影响域分析"章节中，每个需求变更包含以下完整结构算作一条任务：
- **3.1.1 新增/修改/删除xxx需求**
  - a) 依据：xx
  - b) 标识号：xx
  - c) 说明：xx
  - d) 性能指标：xx
  - e) 限制与约束：xx
  - **3.1.1.1 新增需求描述**
  - **3.1.1.2 对关联需求的影响**
  - **3.1.1.3 对关联设计的影响**
  - **3.1.1.4 对关联编码的影响**

### 2. 设计变更任务识别
在影响域分析报告的"3.2 设计变更及其影响域分析"章节中，每个设计变更包含以下完整结构算作一条任务：
- **3.2.1 新增/修改/删除xx设计**
  - **3.2.1.1 新增设计描述**
  - **3.2.1.2 对关联设计的影响**
  - **3.2.1.3 对关联编码的影响**

### 3. 代码变更任务识别
在影响域分析报告的"3.3 代码变更及其影响分析"章节中，每个代码变更包含以下完整结构算作一条任务：
- **3.3.1 新增/修改/删除xx代码**
  - **3.3.1.1 新增代码描述**
  - **3.3.1.2 对关联编码的影响**

### 4. 章节号识别说明
- **有章节号的情况**：严格按照章节号识别任务边界
- **无章节号的情况**：根据文本内容结构和语义判断任务边界，识别类似的完整结构

### 5. 任务去重合并规则
**重要**：多数情况下，需求变更、设计变更、代码变更是独立的任务。但需要识别以下重复情况并合并：

#### 合并条件：
- 当设计变更章节中的内容是对需求变更章节中某个需求的具体设计实现时
- 当代码变更章节中的内容是对需求变更或设计变更的具体代码实现时
- 当多个章节描述的是同一个功能点的不同层面时

#### 合并方法：
1. **识别关联性**：通过功能名称、标识号、描述内容的相似性判断是否为同一变更的不同层面
2. **合并任务**：将相关的需求变更、设计变更、代码变更合并为一个综合任务
3. **任务命名**：使用最核心的变更点命名，如"需求XX的完整实现审查"
4. **任务描述**：包含所有层面的变更内容和影响

#### 独立任务条件：
- 需求变更、设计变更、代码变更描述的是不同功能点
- 变更内容在逻辑上完全独立
- 没有明显的上下级实现关系

## 输出格式要求
请严格按照以下JSON格式输出，包含5个基本字段：

```json
{
  "tasks": [
    {
      "task_id": "1",
      "task_name": "任务名称（简洁明了）",
      "task_description": "详细的任务描述，包含变更内容、影响范围、验证要求等",
      "change_type": "requirement|design|code|combined",
      "original_report_content": "影响域分析报告中对应此任务的原始内容，包括章节标题、变更描述、影响分析等完整信息"
    }
  ]
}
```

## 原始报告内容提取要求
对于每个任务的`original_report_content`字段，请：
1. **完整提取**：包含对应的章节标题、变更描述、影响分析等所有相关内容
2. **保持结构**：保留原始的章节号、标题格式和内容层次
3. **范围准确**：只包含与当前任务直接相关的报告内容
4. **内容完整**：确保包含足够的上下文信息供后续阶段使用

例如，如果任务对应"3.1.1 新增用户认证需求"，则应包含：
- 3.1.1的完整标题
- 该节下的所有子内容（a) 依据、b) 标识号、c) 说明等）
- 相关的影响分析章节（3.1.1.1、3.1.1.2等）

## 任务规划原则

1. **完整性**：确保所有在影响域分析报告中提到的变更都被至少一个任务覆盖
2. **独立性**：任务应尽量独立，避免不必要的重叠
3. **合理性**：正确识别和合并相关联的需求-设计-代码变更
4. **明确性**：每个任务都应有明确的目标和关注点

## 注意事项
1. task_id使用连续数字字符串："1", "2", "3"...
2. task_name要简洁明了，突出变更重点
3. task_description要详细，包含足够信息供后续阶段使用
4. change_type根据变更的主要性质选择最合适的类型
5. 如果报告中没有明确的变更条目，返回空数组[]
6. 不要严格依赖章节号，要根据内容结构和语义进行判断
7. 确保所有变更点都被识别和分析
8. 正确识别同一功能的多层面变更并合并

现在请分析以下影响域分析报告：

{report_content}

请提取并规划回归测试任务："""
